test('MainActivity: NocturneMedia plugin registered before super.onCreate', () => {
  const stock = 'package es.alexcloudweb.nocturne;\n\nimport com.getcapacitor.BridgeActivity;\n\npublic class MainActivity extends BridgeActivity {}\n'
  for (const out of [patchMainActivity(stock), patchMainActivity(LEGACY_ACTIVITY)]) {
    assert.equal(out.split(MEDIA_PLUGIN_REGISTER).length - 1, 1)
    assert.equal(out.split(MEDIA_PLUGIN_IMPORT).length - 1, 1)
    assert.ok(out.indexOf(MEDIA_PLUGIN_REGISTER) < out.indexOf('super.onCreate(savedInstanceState);'))
    assert.ok(out.indexOf(MEDIA_PLUGIN_IMPORT) > out.indexOf('import com.getcapacitor.BridgeActivity;'))
    assert.equal(patchMainActivity(out), out)
  }
  // An activity without an onCreate(super) is not touched.
  const noCreate = LEGACY_ACTIVITY.replace(/\n    @Override[\s\S]*?\n    }\n/, '\n')
  assert.equal(ensureMediaPluginRegistered(noCreate), noCreate)
})

