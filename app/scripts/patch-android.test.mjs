test('versionCodeFor', () => {
  assert.equal(versionCodeFor('1.2.3'), 100200399)
  assert.equal(versionCodeFor('1.0.0', '42'), 42)
  assert.throws(() => versionCodeFor('x'))
  assert.throws(() => versionCodeFor('1.0.0', '-1'))
  assert.throws(() => versionCodeFor('1.1000.0'))
  assert.throws(() => versionCodeFor('21.0.0'))
})

test('versionCodeFor: pre-releases sort below their release and above the previous one', () => {
  const order = ['1.0.3', '1.0.4-alpha.1', '1.0.4-alpha.2', '1.0.4-beta.1', '1.0.4-beta.2', '1.0.4-rc.1', '1.0.4', '1.0.5-beta.1', '1.1.0']
  const codes = order.map((v) => versionCodeFor(v))
  for (let i = 1; i < codes.length; i++) assert.ok(codes[i] > codes[i - 1], `${order[i]} (${codes[i]}) > ${order[i - 1]} (${codes[i - 1]})`)
  // Larger than any code the old scheme produced (1.0.3 -> 1000003), so updates still install.
  assert.ok(versionCodeFor('1.0.4-beta.1') > 1000003)
  assert.equal(versionCodeFor('1.0.4-beta.1'), 100000434)
  assert.ok(versionCodeFor('20.999.999') <= 2_100_000_000)
})

test('styles: items added once, existing overwritten', () => {
  const xml = `<resources>
    <style name="AppTheme" parent="X">
        <item name="android:windowBackground">#fff</item>
    </style>
    <style name="AppTheme.NoActionBar" parent="Y">
    </style>
    <style name="AppTheme.NoActionBarLaunch" parent="Theme.SplashScreen">
        <item name="android:background">@drawable/splash</item>
    </style>
</resources>`
  const out = patchStyles(xml)
  assert.equal(out.split('android:windowBackground').length - 1, 2)
  assert.doesNotMatch(out, /#fff/)
  assert.doesNotMatch(out, /@drawable\/splash/)
  assert.match(out, /postSplashScreenTheme/)
  assert.equal(patchStyles(out), out)
  assert.equal(ensureStyleItems(xml, 'Missing', { a: 'b' }), xml)
})

