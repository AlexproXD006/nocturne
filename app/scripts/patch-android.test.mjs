test('gradle: version, minify, signing; idempotent', () => {
  const opts = { versionName: '2.3.4', versionCode: 2003004 }
  const out = patchBuildGradle(GRADLE, opts)
  assert.match(out, /versionCode 2003004/)
  assert.match(out, /versionName "2\.3\.4"/)
  assert.match(out, /minifyEnabled false/)
  assert.doesNotMatch(out, /minifyEnabled true/)
  for (const v of ['NOCTURNE_KEYSTORE', 'NOCTURNE_KEYSTORE_PASSWORD', 'NOCTURNE_KEY_ALIAS', 'NOCTURNE_KEY_PASSWORD']) {
    assert.match(out, new RegExp(v))
  }
  assert.ok(out.indexOf('signingConfigs {') < out.indexOf('buildTypes {'))
  assert.match(out, /signingConfig signingConfigs\.release/)
  assert.equal(patchBuildGradle(out, opts), out)
})

test('gradle: Media3 dependencies added inside dependencies {}, once, version kept current', () => {
  const out = patchBuildGradle(GRADLE)
  const deps = out.slice(out.indexOf('dependencies {'))
  assert.match(deps, new RegExp(`implementation "androidx\\.media3:media3-session:${MEDIA3_VERSION.replace(/\./g, '\\.')}"`))
  assert.match(deps, /implementation "androidx\.media3:media3-common:/)
  assert.equal(out.split('nocturne:media3-begin').length - 1, 1)
  assert.equal(patchBuildGradle(out), out)
  const old = out.replace(new RegExp(MEDIA3_VERSION.replace(/\./g, '\\.'), 'g'), '1.0.0')
  assert.equal(patchBuildGradle(old), out)
})

