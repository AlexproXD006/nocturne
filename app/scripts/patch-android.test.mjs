test('patchProject applies to a project copy and is idempotent', async (t) => {
  if (!existsSync(join(process.cwd(), 'android/app/build.gradle'))) return t.skip('android/ not generated')
  const dir = await mkdtemp(join(tmpdir(), 'noct-android-'))
  try {
    await cp(join(process.cwd(), 'android'), dir, { recursive: true })
    await patchProject({ androidDir: dir })
    const second = await patchProject({ androidDir: dir })
    assert.deepEqual(second.changed, [])
    const check = await patchProject({ androidDir: dir, check: true })
    assert.deepEqual(check.changed, [])
    const manifest = await readFile(join(dir, 'app/src/main/AndroidManifest.xml'), 'utf8')
    assert.match(manifest, /allowBackup="false"/)
    assert.match(manifest, /NocturneMediaService/)
    const gradle = await readFile(join(dir, 'app/build.gradle'), 'utf8')
    assert.match(gradle, /androidx\.media3:media3-session/)
    const lan = await patchProject({ androidDir: dir, env: { NOCTURNE_LAN_HOSTS: '10.0.0.5' } })
    assert.ok(lan.changed.some((f) => f.endsWith('network_security_config.xml')))
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})
