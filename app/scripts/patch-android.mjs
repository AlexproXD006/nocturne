#!/usr/bin/env node
// Hardens and brands the Capacitor-generated Android project (android/).
//
// Idempotent: running it twice leaves the project byte-for-byte unchanged.
// The patch_* helpers are pure (string in -> string out) so they can be unit-tested
// (see scripts/patch-android.test.mjs). The CLI at the bottom applies them to disk.
//
// Usage:
//   node scripts/patch-android.mjs            patch ./android in place
//   node scripts/patch-android.mjs --check    exit 1 if anything would change
//
// Environment (all optional):
//   NOCTURNE_LAN_HOSTS       comma separated hosts/IPs that may be reached over plain http
//                            (development only, e.g. "192.168.1.50,nas.local")
//   NOCTURNE_VERSION_CODE    integer versionCode (CI sets this; default derives from package.json)
//   NOCTURNE_KEYSTORE & friends are read by Gradle at build time, not by this script.

import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const APP_ID = 'es.alexcloudweb.nocturne'
export const BACKGROUND = '#070a12'
export const ICON_PLATE = '#0d1424'

export const PERMISSIONS = [
  'android.permission.INTERNET',
  'android.permission.WAKE_LOCK',
  'android.permission.FOREGROUND_SERVICE',
  'android.permission.FOREGROUND_SERVICE_MEDIA_PLAYBACK',
  'android.permission.POST_NOTIFICATIONS'
]

export const REQUIRED_CONFIG_CHANGES = ['orientation', 'screenSize', 'keyboardHidden']

/** AndroidX Media3 (system media controls). Bump here; the patch rewrites the gradle block. */
export const MEDIA3_VERSION = '1.11.1'

/** AndroidX WorkManager (periodic background update check, see .../updates/UpdateCheckWorker.java). */
export const WORK_VERSION = '2.11.2'

/** The Media3 session service that backs the now-playing notification (see android/app/src/main/java/.../media/). */
export const MEDIA_SERVICE_CLASS = '.media.NocturneMediaService'
export const MEDIA_SERVICE_MARKER = 'nocturne:media-service'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

