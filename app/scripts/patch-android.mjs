function setTagAttribute(tag, name, value) {
  const attr = new RegExp(`(\\s)${name.replace(/[.:]/g, '\\$&')}="[^"]*"`)
  if (attr.test(tag)) return tag.replace(attr, `$1${name}="${value}"`)
  return tag.replace(/^(<[a-zA-Z]+)/, `$1\n        ${name}="${value}"`)
}

/** Merges `required` into a pipe separated android:configChanges value. */
export function mergeConfigChanges(current, required = REQUIRED_CONFIG_CHANGES) {
  const parts = current ? current.split('|').filter(Boolean) : []
  for (const r of required) if (!parts.includes(r)) parts.push(r)
  return parts.join('|')
}

export function patchManifest(xml) {
  let out = xml

  out = out.replace(/<application\b[^>]*>/, (tag) => {
    let t = tag
    t = setTagAttribute(t, 'android:allowBackup', 'false')
    t = setTagAttribute(t, 'android:usesCleartextTraffic', 'false')
    t = setTagAttribute(t, 'android:networkSecurityConfig', '@xml/network_security_config')
    return t
  })

  out = out.replace(/<activity\b[^>]*>/, (tag) => {
    const m = /android:configChanges="([^"]*)"/.exec(tag)
    return setTagAttribute(tag, 'android:configChanges', mergeConfigChanges(m?.[1]))
  })

  out = ensureMediaService(out)

  const missing = PERMISSIONS.filter((p) => !new RegExp(`<uses-permission[^>]*android:name="${p.replace(/\./g, '\\.')}"`).test(out))
  if (missing.length) {
    const lines = missing.map((p) => `    <uses-permission android:name="${p}" />`).join('\n')
    out = out.replace(/\s*<\/manifest>\s*$/, `\n${lines}\n</manifest>\n`)
  }
  return out
}

const MEDIA_SERVICE_BLOCK = `        <!-- ${MEDIA_SERVICE_MARKER} (generated by scripts/patch-android.mjs) -->
        <service
            android:name="${MEDIA_SERVICE_CLASS}"
            android:exported="true"
            android:foregroundServiceType="mediaPlayback">
            <intent-filter>
                <action android:name="androidx.media3.session.MediaSessionService" />
            </intent-filter>
        </service>
`

/**
 * Declares the Media3 MediaSessionService (exported so system UI, Bluetooth and the lock screen
 * can bind to it; foreground type mediaPlayback for Android 14+). Leaves an existing declaration alone.
 */
export function ensureMediaService(xml) {
  const cls = MEDIA_SERVICE_CLASS.replace(/\./g, '\\.')
  const declared = new RegExp(`<service\\b[^>]*android:name="(?:${APP_ID.replace(/\./g, '\\.')})?${cls}"`)
  if (xml.includes(MEDIA_SERVICE_MARKER) || declared.test(xml)) return xml
  if (!/<\/application>/.test(xml)) return xml
  return xml.replace(/([ \t]*)<\/application>/, (m) => `${MEDIA_SERVICE_BLOCK}${m}`)
}

