const HOST_PATTERN = /^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)*$/i

/** Parses "a, b" into validated hostnames; throws on anything that is not a plain host/IPv4. */
export function parseLanHosts(raw) {
  if (!raw) return []
  const hosts = raw.split(',').map((h) => h.trim()).filter(Boolean)
  for (const h of hosts) if (!HOST_PATTERN.test(h)) throw new Error(`Invalid host in NOCTURNE_LAN_HOSTS: "${h}"`)
  return [...new Set(hosts)]
}

export function networkSecurityConfig(lanHosts = []) {
  const domains = lanHosts.length
    ? `
    <!-- Development only: plain-http hosts enabled through NOCTURNE_LAN_HOSTS. -->
    <domain-config cleartextTrafficPermitted="true">
${lanHosts.map((h) => `        <domain includeSubdomains="false">${h}</domain>`).join('\n')}
    </domain-config>
`
    : `
    <!--
      Cleartext (http) is disabled for every host. To talk to a server on your LAN while
      developing, re-run the patch with the host listed, e.g.

          NOCTURNE_LAN_HOSTS=192.168.1.50 npm run android:sync

      which adds a cleartext-permitted domain-config entry for just that host
      (and lets capacitor.config.ts relax mixed-content blocking for that build).
      Prefer HTTPS with a real certificate for anything beyond a quick test.
    -->
`
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/patch-android.mjs. Do not edit; change the script instead. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
${domains}</network-security-config>
`
}

