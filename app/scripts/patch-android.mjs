/** Adds `<item>`s that are missing from the named <style>; existing items are overwritten. */
export function ensureStyleItems(xml, styleName, items) {
  const re = new RegExp(`(<style\\s+name="${styleName.replace(/\./g, '\\.')}"[^>]*>)([\\s\\S]*?)(</style>)`)
  return xml.replace(re, (_all, open, body, close) => {
    let b = body
    for (const [name, value] of Object.entries(items)) {
      const itemRe = new RegExp(`[ \\t]*<item\\s+name="${name.replace(/[.:]/g, '\\$&')}">[^<]*</item>\\n?`)
      b = b.replace(itemRe, '')
    }
    b = b.replace(/\s+$/, '\n')
    for (const [name, value] of Object.entries(items)) b += `        <item name="${name}">${value}</item>\n`
    return `${open}${b}    ${close}`
  })
}

export function patchStyles(xml) {
  let out = xml
  const surface = {
    'android:windowBackground': '@color/nocturne_background',
    'android:colorBackground': '@color/nocturne_background',
    'android:navigationBarColor': '@color/nocturne_background',
    'android:statusBarColor': '@color/nocturne_background',
    // Dark surface: always draw light system-bar icons, whatever the system theme is.
    'android:windowLightStatusBar': 'false',
    'android:windowLightNavigationBar': 'false'
  }
  out = ensureStyleItems(out, 'AppTheme', surface)
  out = ensureStyleItems(out, 'AppTheme.NoActionBar', surface)
  out = ensureStyleItems(out, 'AppTheme.NoActionBarLaunch', {
    'android:background': '@color/nocturne_background',
    windowSplashScreenBackground: '@color/nocturne_background',
    postSplashScreenTheme: '@style/AppTheme.NoActionBar'
  })
  return out
}

