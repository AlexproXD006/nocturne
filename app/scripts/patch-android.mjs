export async function patchProject({ androidDir = join(ROOT, 'android'), check = false, env = process.env } = {}) {
  const main = join(androidDir, 'app/src/main')
  const res = join(main, 'res')
  if (!existsSync(join(main, 'AndroidManifest.xml'))) {
    throw new Error(`No Android project at ${androidDir}. Run "npm run android:add" first.`)
  }
  const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'))
  const lanHosts = parseLanHosts(env.NOCTURNE_LAN_HOSTS)
  const changed = []
  const apply = async (file, produce) => {
    const prev = existsSync(file) ? await readFile(file, 'utf8') : ''
    const next = produce(prev)
    if (check) {
      if (prev !== next) changed.push(file)
      return
    }
    if (await writeIfChanged(file, next)) changed.push(file)
  }

  await apply(join(main, 'AndroidManifest.xml'), patchManifest)
  await apply(join(res, 'xml/network_security_config.xml'), () => networkSecurityConfig(lanHosts))
  await apply(join(res, 'values/nocturne_colors.xml'), () => nocturneColors())
  await apply(join(res, 'values/styles.xml'), patchStyles)
  await apply(join(res, 'values/ic_launcher_background.xml'), patchLauncherBackground)
  const activity = join(main, 'java', ...APP_ID.split('.'), 'MainActivity.java')
  if (existsSync(activity)) await apply(activity, patchMainActivity)
  await apply(join(androidDir, 'app/build.gradle'), (g) =>
    patchBuildGradle(g, {
      versionName: pkg.version,
      versionCode: versionCodeFor(pkg.version, env.NOCTURNE_VERSION_CODE)
    })
  )

  // Launcher icons, rasterized from resources/icon/*.svg (same icon.svg as the desktop icons).
  const { renderPng } = await import('./make-icons.mjs')
  const svgs = {}
  for (const [kind, name] of Object.entries(ICON_SOURCES)) svgs[kind] = await readFile(join(ROOT, 'resources/icon', name), 'utf8')
  const roundSource = roundSvg(renderPng(svgs.background, 1024), renderPng(svgs.foreground, 1024))
  const sources = { ...svgs, round: roundSource }
  for (const { path, size, kind } of iconPlan()) {
    const file = join(res, path)
    const png = renderPng(sources[kind], size)
    if (check) {
      const prev = existsSync(file) ? await readFile(file) : null
      if (!prev || !prev.equals(png)) changed.push(file)
    } else if (await writeIfChanged(file, png)) changed.push(file)
  }
  return { changed, lanHosts }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  patchProject({ check }).then(
    ({ changed, lanHosts }) => {
      if (lanHosts.length) {
        console.warn(`WARNING: cleartext http enabled for: ${lanHosts.join(', ')} (development builds only).`)
      }
      const rel = (f) => f.replace(`${ROOT}/`, '')
      if (changed.length === 0) console.log('android: already patched, no changes.')
      else {
        console.log(`android: ${check ? 'would change' : 'patched'} ${changed.length} file(s):`)
        for (const f of changed) console.log(`  ${rel(f)}`)
      }
      if (check && changed.length) process.exit(1)
    },
    (err) => {
      console.error(`patch-android failed: ${err.message}`)
      process.exit(1)
    }
  )
}
