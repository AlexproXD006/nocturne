const SIGNING_CONFIG_BLOCK = `    // nocturne:signing-config-begin
    // Release signing is read from the environment so no secret ever lands in the repo.
    // Set all four NOCTURNE_* variables (keystore path must be absolute) to sign; otherwise
    // assembleRelease produces an unsigned APK.
    signingConfigs {
        release {
            def keystorePath = System.getenv('NOCTURNE_KEYSTORE')
            if (keystorePath) {
                storeFile file(keystorePath)
                storePassword System.getenv('NOCTURNE_KEYSTORE_PASSWORD')
                keyAlias System.getenv('NOCTURNE_KEY_ALIAS')
                keyPassword System.getenv('NOCTURNE_KEY_PASSWORD')
            }
        }
    }
    // nocturne:signing-config-end
`

const SIGNING_USE_BLOCK = `            // nocturne:signing-use-begin
            if (System.getenv('NOCTURNE_KEYSTORE')) {
                signingConfig signingConfigs.release
            }
            // nocturne:signing-use-end
`

const MEDIA3_BLOCK = `    // nocturne:media3-begin
    // AndroidX Media3 session: system media controls (notification shade, lock screen, Now Bar).
    implementation "androidx.media3:media3-session:${MEDIA3_VERSION}"
    implementation "androidx.media3:media3-common:${MEDIA3_VERSION}"
    // nocturne:media3-end
`

const WORK_BLOCK = `    // nocturne:work-begin
    // AndroidX WorkManager: periodic "new version available" check that runs with the app closed.
    implementation "androidx.work:work-runtime:${WORK_VERSION}"
    // nocturne:work-end
`

export function patchBuildGradle(gradle, { versionName, versionCode } = {}) {
  let out = gradle

  if (versionCode !== undefined) out = out.replace(/versionCode\s+\d+/, `versionCode ${versionCode}`)
  if (versionName !== undefined) out = out.replace(/versionName\s+"[^"]*"/, `versionName "${versionName}"`)

  // WebView app: nothing to shrink. R8 would only risk stripping Capacitor plugin classes.
  out = out.replace(/minifyEnabled\s+true/g, 'minifyEnabled false')
  if (!/minifyEnabled/.test(out)) {
    out = out.replace(/(buildTypes\s*\{\s*release\s*\{\n)/, `$1            minifyEnabled false\n`)
  }

  const configRe = /[ \t]*\/\/ nocturne:signing-config-begin[\s\S]*?\/\/ nocturne:signing-config-end\n/
  if (configRe.test(out)) out = out.replace(configRe, () => SIGNING_CONFIG_BLOCK)
  else out = out.replace(/^([ \t]*)buildTypes\s*\{/m, (m) => `${SIGNING_CONFIG_BLOCK}    ${m.trimStart()}`)

  const useRe = /[ \t]*\/\/ nocturne:signing-use-begin[\s\S]*?\/\/ nocturne:signing-use-end\n/
  if (useRe.test(out)) out = out.replace(useRe, () => SIGNING_USE_BLOCK)
  else out = out.replace(/(buildTypes\s*\{\s*release\s*\{\n)/, (m) => `${m}${SIGNING_USE_BLOCK}`)

  const media3Re = /[ \t]*\/\/ nocturne:media3-begin[\s\S]*?\/\/ nocturne:media3-end\n/
  if (media3Re.test(out)) out = out.replace(media3Re, () => MEDIA3_BLOCK)
  else out = out.replace(/^dependencies\s*\{[ \t]*\n/m, (m) => `${m}${MEDIA3_BLOCK}`)

  const workRe = /[ \t]*\/\/ nocturne:work-begin[\s\S]*?\/\/ nocturne:work-end\n/
  if (workRe.test(out)) out = out.replace(workRe, () => WORK_BLOCK)
  else if (media3Re.test(out)) out = out.replace(media3Re, (m) => `${m}${WORK_BLOCK}`)
  else out = out.replace(/^dependencies\s*\{[ \t]*\n/m, (m) => `${m}${WORK_BLOCK}`)

  return out
}

/**
 * Derives a monotonically increasing versionCode from a semver string, leaving
 * room for pre-releases so they always sort below their own release:
 *
 *   code = (major·1e6 + minor·1e3 + patch)·100 + suffix
 *   suffix = 99 for a release; for `alpha.N` 1+N, `beta.N` 33+N, `rc.N` 65+N
 *            (N capped at 31; other labels count as alpha).
 *
 * So 1.0.4-alpha.2 < 1.0.4-beta.1 < 1.0.4-rc.1 < 1.0.4 < 1.0.5-beta.1, and every
 * code is larger than the old scheme's (≤ 2000999999 / 100), so devices that
 * installed an old-scheme build can still update.
 */
export function versionCodeFor(version, override) {
  if (override !== undefined && override !== '') {
    const n = Number(override)
    if (!Number.isInteger(n) || n < 1 || n > 2_100_000_000) throw new Error(`Invalid NOCTURNE_VERSION_CODE: ${override}`)
    return n
  }
  const m = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?(?:\+.*)?$/.exec(String(version).trim())
  if (!m) throw new Error(`Cannot derive versionCode from version "${version}"`)
  const [major, minor, patch] = [Number(m[1]), Number(m[2]), Number(m[3])]
  if (minor > 999 || patch > 999 || major > 20) throw new Error(`Version out of range: ${version}`)
  let suffix = 99
  if (m[4]) {
    const [label, num] = m[4].split('.')
    const base = label === 'rc' ? 65 : label === 'beta' ? 33 : 1
    const n = Math.min(31, Math.max(0, parseInt(num ?? '0', 10) || 0))
    suffix = base + n
  }
  return (major * 1_000_000 + minor * 1_000 + patch) * 100 + suffix
}

