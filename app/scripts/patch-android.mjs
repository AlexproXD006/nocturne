export const MAIN_ACTIVITY_MARKER = 'nocturne:notification-permission'
export const MEDIA_PLUGIN_IMPORT = 'import es.alexcloudweb.nocturne.media.NocturneMediaPlugin;'
export const MEDIA_PLUGIN_REGISTER = 'registerPlugin(NocturneMediaPlugin.class);'
export const UPDATES_PLUGIN_IMPORT = 'import es.alexcloudweb.nocturne.updates.NocturneUpdatesPlugin;'
export const UPDATES_PLUGIN_REGISTER = 'registerPlugin(NocturneUpdatesPlugin.class);'

/** App-local Capacitor plugins, registered in this order before super.onCreate. */
export const APP_PLUGINS = [
  { importLine: MEDIA_PLUGIN_IMPORT, register: MEDIA_PLUGIN_REGISTER },
  { importLine: UPDATES_PLUGIN_IMPORT, register: UPDATES_PLUGIN_REGISTER }
]

/**
 * Android 13+ needs a runtime grant of POST_NOTIFICATIONS before the media
 * notification (lock-screen / shade controls) becomes visible, so the activity asks.
 * It also registers the app-local NocturneMedia and NocturneUpdates plugins (local plugins are not
 * auto-registered by `cap sync`; registration must happen before super.onCreate).
 */
export function mainActivityJava(packageName = 'es.alexcloudweb.nocturne') {
  return `package ${packageName};

import android.Manifest;
import android.content.pm.PackageManager;
import android.os.Build;
import android.os.Bundle;
import com.getcapacitor.BridgeActivity;
${MEDIA_PLUGIN_IMPORT}
${UPDATES_PLUGIN_IMPORT}

public class MainActivity extends BridgeActivity {
    // ${MAIN_ACTIVITY_MARKER} (generated by scripts/patch-android.mjs)
    private static final int REQUEST_POST_NOTIFICATIONS = 1001;

    @Override
    public void onCreate(Bundle savedInstanceState) {
        ${MEDIA_PLUGIN_REGISTER}
        ${UPDATES_PLUGIN_REGISTER}
        super.onCreate(savedInstanceState);
        if (Build.VERSION.SDK_INT >= 33
                && checkSelfPermission(Manifest.permission.POST_NOTIFICATIONS) != PackageManager.PERMISSION_GRANTED) {
            requestPermissions(new String[] { Manifest.permission.POST_NOTIFICATIONS }, REQUEST_POST_NOTIFICATIONS);
        }
    }
}
`
}

/**
 * Adds one app-local plugin registration (right before super.onCreate) and its import (after the
 * last import) to an activity that has an onCreate calling super. Already registered: unchanged.
 */
export function ensurePluginRegistered(java, { importLine, register }) {
  if (java.includes(register)) return java
  const superCall = /^([ \t]*)super\.onCreate\(\s*savedInstanceState\s*\);/m
  if (!superCall.test(java)) return java
  let out = java.replace(superCall, (m, indent) => `${indent}${register}\n${m}`)
  if (!out.includes(importLine)) {
    const imports = [...out.matchAll(/^import\s+[\w.]+(?:\.\*)?;[ \t]*\n/gm)]
    const last = imports[imports.length - 1]
    if (last) {
      const at = last.index + last[0].length
      out = `${out.slice(0, at)}${importLine}\n${out.slice(at)}`
    } else {
      out = out.replace(/^(\s*package\s+[\w.]+\s*;[ \t]*\n)/m, `$1\n${importLine}\n`)
    }
  }
  return out
}

/** Adds the NocturneMedia plugin registration to an activity that has an onCreate calling super. */
export function ensureMediaPluginRegistered(java) {
  return ensurePluginRegistered(java, APP_PLUGINS[0])
}

/** Registers every app-local plugin (NocturneMedia, NocturneUpdates) in APP_PLUGINS order. */
export function ensureAppPluginsRegistered(java) {
  return APP_PLUGINS.reduce((out, plugin) => ensurePluginRegistered(out, plugin), java)
}

/**
 * Replaces the stock empty activity; an already patched file only gets the app-local plugin
 * registrations added (if missing). A customised activity without the marker is left alone.
 */
export function patchMainActivity(java) {
  if (java.includes(MAIN_ACTIVITY_MARKER)) return ensureAppPluginsRegistered(java)
  const pkg = /^\s*package\s+([\w.]+)\s*;/m.exec(java)?.[1]
  const stock = /public\s+class\s+MainActivity\s+extends\s+BridgeActivity\s*\{\s*\}/.test(java)
  return stock && pkg ? mainActivityJava(pkg) : java
}

